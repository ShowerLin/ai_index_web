from paths import DATA_ROOT, BUILD_ROOT
"""Read cached hyperscaler inputs without modifying the source workbook."""
from pathlib import Path
import hashlib
import json
import openpyxl

root = BUILD_ROOT
source = DATA_ROOT / "Indexlist.xlsx"
book = openpyxl.load_workbook(source, data_only=True, read_only=True)
sheet = book["Hyperscaler Core Data Value"]
coverage=json.loads((DATA_ROOT/'data/reference/financial_publication_coverage.json').read_text(encoding='utf-8'))['series']['roic']

field_map = {
    "nopat": "#NOPAT",
    "cashAndShortTermInvestments": "#cash_and_short_term_investments",
    "totalDebt": "#total_debt",
    "operatingLeaseLiabilities": "#lease_liabilities_operating",
    "financeLeaseLiabilitiesCurrent": "#lease_liabilities_finance_st",
    "financeLeaseLiabilitiesLongTerm": "#lease_liabilities_finance_lt",
    "shareholdersEquity": "#shareholders_equity",
}

company_specs = [
    ("MSFT", "Microsoft", "Direct Bloomberg NOPAT and core invested-capital fields available."),
    ("GOOGL", "Alphabet", "Direct Bloomberg NOPAT and core invested-capital fields available; long-term investments are not deducted."),
    ("AMZN", "Amazon", "Direct Bloomberg NOPAT and core invested-capital fields available; long-term investments are not deducted."),
    ("META", "Meta", "Direct Bloomberg NOPAT and core invested-capital fields available."),
    ("ORCL", "Oracle", "Direct Bloomberg NOPAT and core invested-capital fields available; latest period is March 2026 and remains calendarized."),
]

companies = []
for ticker, name, note in company_specs:
    start = next(cell.column for cell in sheet[1] if cell.value == f"{ticker} US Equity")
    columns = {sheet.cell(2, column).value: column for column in range(start, start + 11)}
    missing_headers = [source_name for source_name in field_map.values() if source_name not in columns]
    if missing_headers:
        raise ValueError(f"Missing ROIC fields for {ticker}: {missing_headers}")

    records = []
    for row in range(3, sheet.max_row + 1):
        date = sheet.cell(row, 1).value
        if isinstance(date, (int, float)):
            date = openpyxl.utils.datetime.from_excel(date)
        if not hasattr(date, "strftime"):
            continue
        period=date.strftime('%Y-%m-%d')
        if period not in coverage[ticker]:continue
        record = {"period": date.strftime("%Y-%m-%d"), "sourceRow": row}
        for output_name, source_name in field_map.items():
            value = sheet.cell(row, columns[source_name]).value
            record[output_name] = value / 1e9 if isinstance(value, (int, float)) and output_name in coverage[ticker][period] else None
        records.append(record)

    if not records:raise ValueError(f'No dated ROIC observations for {ticker}')
    companies.append({
        "ticker": ticker,
        "name": name,
        "readiness": "ready",
        "readinessReason": note,
        "financeLeasesExcludedFromDebt": True if ticker == "MSFT" else None,
        "quarters": records,
    })

payload = {
    "source": "Indexlist.xlsx",
    "sheet": sheet.title,
    "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "unit": "USD billions",
    "basis": "Cached Bloomberg BQ data; direct Bloomberg NOPAT and simplified core invested capital.",
    "companies": companies,
}

output = root / "app" / "roic-snapshot.ts"
output.write_text(
    "// Generated by scripts/extract-roic.py. Do not edit inputs manually.\n"
    + "export const roicSnapshot = "
    + json.dumps(payload, indent=2)
    + " as const;\n",
    encoding="utf-8",
)
print(f"Extracted ROIC inputs for {len(companies)} companies")
