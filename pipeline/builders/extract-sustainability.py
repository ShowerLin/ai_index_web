from paths import DATA_ROOT, BUILD_ROOT
"""Read the cached workbook without modifying it; emit auditable quarterly inputs."""
from pathlib import Path
import hashlib
import json
import openpyxl

root = BUILD_ROOT
source = DATA_ROOT / 'Indexlist.xlsx'
book = openpyxl.load_workbook(source, data_only=True, read_only=True)
sheet = book['Hyperscaler Core Data Value']
coverage=json.loads((DATA_ROOT/'data/reference/financial_publication_coverage.json').read_text(encoding='utf-8'))['series']['sustainability']
companies = []
for ticker, name in [('MSFT', 'Microsoft'), ('GOOGL', 'Alphabet'), ('AMZN', 'Amazon'), ('META', 'Meta'), ('ORCL', 'Oracle')]:
    start = next(c.column for c in sheet[1] if c.value == ticker + ' US Equity')
    columns = {sheet.cell(2, c).value: c for c in range(start, start + 11)}
    records = []
    for row in range(3, sheet.max_row + 1):
        date = sheet.cell(row, 1).value
        if isinstance(date, (int, float)):
            date = openpyxl.utils.datetime.from_excel(date)
        if not hasattr(date, 'strftime'):
            continue
        period=date.strftime('%Y-%m-%d')
        if period not in coverage[ticker]:continue
        values = [sheet.cell(row, columns[field]).value for field in ['#cash_flow_from_operations', '#cash_capex']]
        valid = all(isinstance(v, (int, float)) for v in values) and all(f in coverage[ticker][period] for f in ['cfo','capex'])
        if valid and values[1] > 0:
            raise ValueError(f'Unexpected capex sign: {ticker}, {date}')
        records.append({'period': date.strftime('%Y-%m-%d'), 'cfo': values[0] / 1e9 if valid else None,
                        'capex': -values[1] / 1e9 if valid else None,
                        'sourceRange': f'{openpyxl.utils.get_column_letter(columns["#cash_flow_from_operations"])}{row}:{openpyxl.utils.get_column_letter(columns["#cash_capex"])}{row}'})
    if not records:raise ValueError(f'No dated cash observations for {ticker}')
    companies.append({'ticker': ticker, 'name': name, 'quarters': records})
payload = {'source': 'Indexlist.xlsx', 'sheet': sheet.title, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
           'unit': 'USD billions', 'basis': 'Cached Bloomberg BQ data; Oracle calendarization requires reconciliation.', 'companies': companies}
(root / 'app' / 'sustainability-snapshot.ts').write_text('// Generated by scripts/extract-sustainability.py. Do not edit inputs manually.\nexport const sustainabilitySnapshot = ' + json.dumps(payload, indent=2) + ';\n', encoding='utf-8')
print('Extracted cash flow and cash capex for', len(companies), 'companies')
